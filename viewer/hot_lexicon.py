def normalize(topic: str) -> str:
    """把任意热词归一到规范词条；未命中返回原词。"""
    t = (topic or "").strip()
    if t in ENTRIES:
        return t
    return ALIASES.get(t, t)


def entry_of(topic: str) -> dict | None:
    """取规范词条对应的传导条目（已归一）；不存在返回 None。"""
    return ENTRIES.get(normalize(topic))


def all_topics() -> list[str]:
    """返回全部规范词条（传导表主键）。"""
    return list(ENTRIES.keys())


def match_terms(topic: str) -> list[str]:
    """返回该规范词条在帖文中应匹配的所有字面串：规范词本身 + 其全部别名。

    例如「机器人」会同时匹配「人形机器人 / 减速器 / 伺服 / 丝杠 / 谐波」，
    因此即便帖文只写了别名，也能归到正确的主线。
    """
    canon = normalize(topic)
    terms = [canon]
    for alias, target in ALIASES.items():
        if target == canon and alias != canon:
            terms.append(alias)
    return terms
