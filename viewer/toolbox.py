def _apply_template(tmpl: str):
    def _f(con, codes, params) -> dict:
        # 注意：`stock_strategy_picks.updated` 实测**全是空串**（列建了但没写）。
        # 所以不能拿 MAX(updated) 当批次键 —— 空串会被误判成「该模板无数据」，
        # 于是 1188 只的名单在工具包里变成 0 只。有值才按批次过滤，没值就整模板取。
        latest = _latest(con, "SELECT MAX(updated) FROM stock_strategy_picks WHERE template=?",
                         (tmpl,))
        got = {}
        CH = 400
        for i in range(0, len(codes), CH):
            chunk = codes[i:i + CH]
            ph = ",".join("?" * len(chunk))
            if latest:
                rows = con.execute(
                    "SELECT code,score,reasons FROM stock_strategy_picks"
                    " WHERE template=? AND updated=? AND code IN (%s)" % ph,
                    [tmpl, latest] + chunk)
            else:
                rows = con.execute(
                    "SELECT code,score,reasons FROM stock_strategy_picks"
                    " WHERE template=? AND code IN (%s)" % ph, [tmpl] + chunk)
            for r in rows:
                got[str(r[0])] = (r[1], r[2])
        total = 0
        try:
            total = con.execute("SELECT COUNT(*) FROM stock_strategy_picks WHERE template=?",
                                (tmpl,)).fetchone()[0]
        except Exception:  # noqa: BLE001
            pass
        if not total:
            return _res([], {c: "该模板尚无产出" for c in codes}, {},
                        "模板 %s 在库里没有记录" % tmpl)
        kept, dropped, score, marks = [], {}, {}, {}
        for c in codes:
            v = got.get(c)
            if not v:
                dropped[c] = "不在「%s」模板名单内（全库 %d 只）" % (tmpl, total)
                continue
            kept.append(c)
            score[c] = float(v[0] or 0)
            marks[c] = str(v[1] or "")[:120]
        return _res(kept, dropped, score,
                    "模板 %s%s：%d 只 → %d 只（全库该模板 %d 只）"
                    % (tmpl, ("·批次 " + latest) if latest else "·无批次日期",
                       len(codes), len(kept), total),
                    {"marks": marks})
    return _f


