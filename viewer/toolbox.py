    for k in ("params_schema", "default_params"):
        try:
            d[k] = json.loads(d.get(k) or ("[]" if k == "params_schema" else "{}"))
        except Exception:  # noqa: BLE001
            d[k] = [] if k == "params_schema" else {}
    # 分类拆成列表 + 中文名 + 持有期标注 + 判据回看尺度，前端直接渲染，不用自己 split
    # （2026-11-05：从「适用板块」改成「持有周期分类」，字段名保持 pillars 不变 ——
    #   数据库列名与前端读的键都不动，只换内容口径，避免一次改分类就要迁库。）
    d["pillar_list"] = [x for x in (d.get("pillars") or "").split(",") if x]
