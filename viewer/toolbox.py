def _blank(codes) -> tuple[list, dict, dict]:
    return list(dict.fromkeys([str(c) for c in (codes or []) if c])), {}, {}


def _res(kept, dropped, score, note, extra=None) -> dict:
    out = {"kept": kept, "dropped": dropped, "score": score,
           "stats": {"in": len(kept) + len(dropped), "out": len(kept)},
           "note": note}
    if extra:
        out.update(extra)
    return out


def _latest(con, sql: str, args=()) -> str:
    try:
        r = con.execute(sql, args).fetchone()
        return (r and str(r[0])) or ""
    except Exception:  # noqa: BLE001
        return ""


