def _apply_gate(con, codes, params) -> dict:
    from viewer import gate as G
    g = G.evaluate(con, codes)
    hard_only = bool(int(params.get("hard_only", 1) or 0))
    kept, dropped, marks = [], {}, {}
    for c in codes:
        e = g.get(c) or {}
        if e.get("hard"):
            dropped[c] = "硬否决：" + "；".join(e["hard"])
            continue
        kept.append(c)
        # 软否决不淘汰，只把原因挂在行上让人自己判断（这是「闸门」与「筛子」的分界：
        # 硬项决定生死，软项只决定排序/提示，不能替人做决定）
        soft = e.get("soft") or []
        pen = float(e.get("penalty") or 0.0)
        if soft:
            marks[c] = ("⚠ 软否决 %d 项（−%.0f 分）：%s" % (len(soft), pen, "；".join(soft))
                        if not hard_only else "⚠ " + "；".join(soft))
    note = "硬否决 %d 只（净资产为负 / 微盘 / 资不抵债 / 深度亏损）" % len(dropped)
    if marks:
        note += "；软否决 %d 只（只打标不剔除）" % len(marks)
    return _res(kept, dropped, {}, note, {"marks": marks})


# ---- 箱体谷底 ----------------------------------------------------
# ★ 2026-11-06 审计 P0-04：这里的默认 `pos_max` 曾经是 **1.0**。
#   意思是「箱体位置 0%~100% 都算箱体谷底」—— 名字叫谷底，行为却接受箱顶。
#   实测那批 653 只输出里 3 只超过 1/3（000731 / 002069 各 35%、002088 34%），
#   于是「今天不会把非箱底当箱底」只靠运气成立，契约上没有任何保证。
#   现在默认 1/3，并且位置是**硬判据**而不是可调松的偏好：
#   调到 1.0 仍然能跑（老参数要兼容），但会被标注为「参数已放宽，名称与行为不一致」。
BOX_POS_MAX = 0.333


def _apply_box(con, codes, params) -> dict:
    from viewer import universe_box as ub
    from viewer import localfeed as _lf
    min_dwell = float(params.get("min_dwell", 0.15))
    pos_max = float(params.get("pos_max", BOX_POS_MAX))
    min_years = float(params.get("min_years", 0.5))
    try:
        names = _lf.pool(with_names=True)
    except Exception:  # noqa: BLE001
        names = {}
    # 取数路径要按池子大小分流，不能一律 `load_bars(codes)`：
    # 实测把 5012 个代码显式传给 `ohlcv_bulk` 要 **42 秒**，而不带 codes 走全宇宙批量只要 4 秒
    # （前者要按 code 拼条件，后者是一次顺序扫描）。漏斗第一级几乎总是全市场，
    # 所以大池子时先取全量再在内存里求交集 —— 同一份数据，快十倍。
    # 小池子（例如已经收窄到几十只）则相反：没必要为 50 只读 5000 只的 K 线。
    if len(codes) >= 2000:
        _full = ub.load_bars(None)
        kl = {c: _full[c] for c in codes if c in _full} if _full else {}
    else:
        kl = ub.load_bars(codes)
    kept, dropped, score, marks = [], {}, {}, {}
    for c in codes:
        bars = kl.get(c)
        if not bars:
            dropped[c] = "无本地日线（kbase 缺这只票）"
            continue
        m = ub.scan_one(bars)
        if not m:
            dropped[c] = "形态未过一级门槛（数据不足 / 日均成交额过低 / 不在 750 日低位 / 箱体不规整）"
            continue
        if m["box_years"] < min_years:
            dropped[c] = "箱体仅 %.1f 年 < %.1f 年" % (m["box_years"], min_years)
            continue
        if m["pos"] > pos_max:
            dropped[c] = "箱体位置 %.0f%% > %.0f%%" % (m["pos"] * 100, pos_max * 100)
            continue
        if m["dwell_ratio"] < min_dwell:
            dropped[c] = "谷底驻留 %.0f%% < %.0f%%（刚到谷底，不是磨在谷底）" % (
                m["dwell_ratio"] * 100, min_dwell * 100)
            continue
        if m["touches"] < ub.TOUCH_MIN:
            dropped[c] = "箱底触及仅 %d 次（< %d 次，不像真箱体）" % (m["touches"], ub.TOUCH_MIN)
            continue
        sc = ub.score_one(m)
        score[c] = sc["score"]
        marks[c] = ("箱体 %.1f 年 · 位置 %.0f%% · 驻留 %.0f%% · 最长连续 %d 日 · 触及 %d 次"
                    % (m["box_years"], m["pos"] * 100, m["dwell_ratio"] * 100,
                       m["dwell_max_run"], m["touches"]))
        kept.append(c)
    note = "箱体筛：%d 只 → %d 只（驻留下限 %.0f%%）" % (len(codes), len(kept), min_dwell * 100)
    if pos_max > BOX_POS_MAX + 1e-9:
        # 放宽参数不是错，但必须让人看见代价：位置 40% 的票不是箱底，是箱体中部。
        note += "；⚠ 位置上限被放宽到 %.0f%%，超过 1/3 的票不是箱底" % (pos_max * 100)
    # 这句话不是免责声明，是审计 §4.5 的结论落地：14.8 年条件化回测里箱底分位
    # 对 T+20/T+60/T+120 的超额分别是 -0.036 / -0.409 / -0.594pp（t 全部不显著），
    # 所以「到了箱底」只等于「值得研究」，不等于「可以买」。
    note += "；箱底仅输出观察，不构成买入依据"
    return _res(kept, dropped, score, note, {"marks": marks})


