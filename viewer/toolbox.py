    d["advisory"] = int(d.get("advisory") or 0)
    # 分数方向与一句话说明，前端直接显示（不在前端再判断一次，免得两边口径漂移）
    d["score_dir"] = score_dir_of(d["tool_key"])
    d["score_note"] = score_note_of(d["tool_key"])
    return d


