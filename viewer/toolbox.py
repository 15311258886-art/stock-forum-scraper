# ⑥ 三期：GitHub 开源规则的筛选器引擎（2026-11-04）
# ================================================================
# 这一节把 `oss_mine.RULE_SEEDS` 里那 11 条**已经用本项目严格口径回测过**的开源规则，
# 做成筛台里可点、可调参的筛选器。规则的判据口径照 `oss_mine.py`，字段口径照
# `hypo._iter_hits()` —— 两处都不许自己另算一套。
#
# 三条纪律（改这一节前先读）
#
#  1. **不重算一套特征**：全部字段取自 `stock_indicators_daily`，算法与 hypo 完全同源
#     （见 `_build_oss_snapshot` 的注释）。一旦这里另算一套，卡片上写的「实测超额」
#     和工具实际筛出来的票就再也对不上了，那是最难查的一类错。
#  2. **逐只独立判断**：每个判据只看这只票自己的字段，不看池子的分布、不做排名截断。
#     这是筛台「每个工具对全宇宙只算一次、之后只做集合求交」能成立的前提 ——
#     只要有一个工具偷偷用了分位，它的结果就会随输入池变化，求交出来的数字是错的。
#  3. **不设淘汰门槛**：11 条全部上架（含跑输的那些），由用户自己用下来决定。
#     统计检验只用来写 `caveat` 里的数字，不用来替他决定「做不做」。
#
# 性能：11 个工具共用**同一份全市场快照**（按交易日 + 库文件缓存 15 分钟）。
# 冷启动一次约 1.8 秒（0.009 秒取当日指标 + 1.7 秒滚 251 天收盘），
# 之后每个工具只是对 5260 条记录做一遍字典判断，毫秒级 —— 比逐工具重算
# （每个 6~8 秒）快两个量级，而且都在 `toolbox_stack` 的 worker 线程里跑。


class _Snap(NamedTuple):
    """一只票在【最近交易日】的全部判据字段（口径见 `_build_oss_snapshot`）。"""

    code: str
    name: str
    close: float | None
    ma5: float | None
    ma20: float | None
    ma60: float | None
    rsi6: float | None
    atr_pct: float | None
    volume_ratio: float | None
    ret1: float | None
    ret2: float | None
    ret5: float | None
    mom20: float | None
    dist_high250: float | None
    ma20_dev: float | None


# 251 = 250 个交易日前 + 当日，正好是 hypo 算 dist_high250 的窗口长度。
_OSS_HIST_DAYS = 251
# 快照缓存有效期：日 K 一天只变一次，但盘中可能有回补写库，15 分钟兜一次底。
_OSS_SNAP_TTL = 900.0
_OSS_SNAP: dict = {"key": "", "date": "", "at": 0.0, "snap": {}}
_OSS_SNAP_LOCK = threading.Lock()


def _num(v, default: float) -> float:
    """参数取数：前端可能给字符串 / None / 空串，一律落到一个能用的数上。"""
    try:
        out = float(v)
    except (TypeError, ValueError):
        return float(default)
    return out if out == out else float(default)        # NaN 也退回默认值


def _pct(cur: float | None, prev: float | None) -> float | None:
    """涨跌幅（%）。prev 缺失或非正 → None，让「判不了」和「不满足」能被区分开。"""
    if not cur or not prev or prev <= 0:
        return None
    return (cur / prev - 1.0) * 100.0


def _f(v) -> float | None:
    """把指标表里的值转成 float；空值 / 0 一律当「没有」。"""
    try:
        out = float(v)
    except (TypeError, ValueError):
        return None
    return out if out > 0 else None


def _is_st(name: str) -> bool:
    """名称里带 ST 的票（ST / *ST / S*ST / SST）。A 股正常公司名是中文，不会误伤。"""
    return "ST" in str(name or "").upper()


def _limit_up_thr(code: str) -> float:
    """当日「涨停」的涨幅门槛（近似值）。

    主板（60x / 000 / 001 / 002 / 003 等）10% → 判 9.8%；
    创业板（300 / 301）与科创板（688 / 689）20% → 判 19.8%；
    北交所（4xx / 8xx / 920）30% → 判 29.8%。

    ★ 局限（写在这里而不是藏着）：ST 股实际是 5%，这里没有单独判 —— 要剔除它们
      请用 `skip_st` 那个参数；新股上市首日与复牌首日不设涨跌幅，会被误判成涨停。
    """
    c = str(code or "")
    if c[:3] in ("300", "301", "688", "689"):
        return 19.8
    if c[:1] in ("4", "8") or c[:3] == "920":
        return 29.8
    return 9.8


def _oss_db_key(con) -> str:
    """缓存键里的库标识：同一个 app.db 的多个连接要共用一份快照。"""
    try:
        for r in con.execute("PRAGMA database_list"):
            if str(r[1]) == "main":
                return str(r[2] or "")
    except Exception:  # noqa: BLE001
        log.exception("读取库路径失败（快照缓存退化为按进程共享）")
    return "?"


def _build_oss_snapshot(con, latest: str) -> dict:
    """构建最近交易日的全市场判据快照 → {code: _Snap}。

    取数为什么分两步（而不是一条窗口函数 SQL）：这张表主键是 (date, code)，按 code
    分组必须重排序，实测 1.3M 行带 `MAX(... 250 PRECEDING)` 要 **30 秒**；
    拆成「按 date 顺序流式滚一遍 + 当日指标行直读」只要 **1.7 + 0.01 秒**。

    口径与 `hypo._iter_hits()` 逐字段对齐：
      · ret1  = 收盘 ÷ 前一日收盘 − 1
      · ret2  = 收盘 ÷ 2 个交易日前收盘 − 1
      · ret5  = 收盘 ÷ 6 个交易日前收盘 − 1   ← 见下面的 ⚠️
      · mom20 = 收盘 ÷ 21 个交易日前收盘 − 1  ← 见下面的 ⚠️
      · dist_high250 = 收盘 ÷ 近 251 个交易日最高收盘 − 1
      · ma20_dev / atr_pct 直接用指标表算好的值（不重算，避免两套数）

    ⚠️ ret5 / mom20 的「差一根 K 线」是**刻意照抄 hypo**（`closes[-6]` / `closes[-21]`）：
       这两条规则的回测数字就是按这个口径跑出来的，改成"正确"的 5 / 20 根，
       卡片上的超额和工具实际命中就对不上了。ret1 / ret2 没有这个问题。
    """
    cal = [str(r[0]) for r in con.execute(
        "SELECT DISTINCT date FROM stock_indicators_daily WHERE date<=? "
        "ORDER BY date DESC LIMIT ?", (latest, _OSS_HIST_DAYS))]
    if not cal:
        return {}
    since = cal[-1]
    # ① 滚动窗口：按交易日升序流式走，逐只维护「最近 22 个收盘」+「窗口内最高收盘」。
    #    22 = 算 mom20 要 21 个历史收盘 + 当日。
    hist: dict[str, deque] = {}
    high: dict[str, float] = {}
    try:
        cur = con.execute(
            "SELECT code,close FROM stock_indicators_daily"
            " WHERE date>=? AND date<=? AND close>0 ORDER BY date", (since, latest))
        for code, close in cur:
            code = str(code)
            dq = hist.get(code)
            if dq is None:
                dq = hist[code] = deque(maxlen=22)
            dq.append(float(close))
            h = high.get(code)
            if h is None or float(close) > h:
                high[code] = float(close)
    except Exception:  # noqa: BLE001
        log.exception("开源规则：滚动历史取数失败")
        return {}
    # ② 当日指标行：均线 / RSI / 量比 / ATR 都是表里算好的，直接读，不重算。
    try:
        rows = con.execute(
            "SELECT code,name,close,ma5,ma20,ma60,rsi6,atr,volume_ratio"
            " FROM stock_indicators_daily WHERE date=? AND close>0", (latest,)).fetchall()
    except Exception:  # noqa: BLE001
        log.exception("开源规则：当日指标取数失败")
        return {}

    # ③ 名称以 `stock_names` 为准，**不用指标表里的 name**：
    #    实测 `stock_indicators_daily.name` 是「摘掉 ST 标记」的干净快照 —— 今天 5260 行里
    #    一个含 ST 的都没有，而 `stock_names` 里有 512 个 ST/`*ST` 代码，且覆盖今天全部
    #    5260 只。用指标表的 name，`skip_st` 会永远剔不掉任何票，是一项静默失效。
    #    局限：`stock_names` 存的是**当前**名称，所以它只对「判断最新交易日」有效 ——
    #    本模块的工具本来就只判最新交易日，不受影响；将来若要回看历史某天，
    #    必须另找带日期的名称来源，不能拿这张表顶。
    names: dict[str, str] = {}
    try:
        for code, name in con.execute("SELECT code,name FROM stock_names"):
            if code:
                names[str(code)] = str(name or "")
    except Exception:  # noqa: BLE001
        log.exception("开源规则：股票名称表读取失败（skip_st 将退化为用指标表名称）")

    out: dict[str, _Snap] = {}
    for code, name, close, ma5, ma20, ma60, rsi6, atr, vr in rows:
        code = str(code)
        closef = _f(close)
        if closef is None:
            continue
        back = hist.get(code)
        n_hist = len(back) if back else 0
        ma20f = _f(ma20)
        out[code] = _Snap(
            code=code,
            name=names.get(code) or str(name or ""),
            close=closef,
            ma5=_f(ma5),
            ma20=ma20f,
            ma60=_f(ma60),
            rsi6=_f(rsi6),
            atr_pct=(float(atr) / closef * 100.0) if _f(atr) else None,
            volume_ratio=_f(vr),
            ret1=_pct(closef, back[-2] if n_hist >= 2 else None),
            ret2=_pct(closef, back[-3] if n_hist >= 3 else None),
            ret5=_pct(closef, back[-7] if n_hist >= 7 else None),
            mom20=_pct(closef, back[-22] if n_hist >= 22 else None),
            dist_high250=_pct(closef, high.get(code)),
            ma20_dev=_pct(closef, ma20f),
        )
    return out


def oss_snapshot(con) -> tuple[str, dict]:
    """最近交易日 + 全市场判据快照（11 个工具共用一份，按交易日缓存）。

    为什么让它常驻进程：单个工具 6~8 秒是取数成本，而 11 条规则要的是**同一份**数据。
    不共用的话，用户在筛台上点 11 次就是 80 秒；共用之后第一个 1.8 秒、其余是毫秒。
    缓存键里带**交易日**，日 K 一变立刻失效 —— 绝不拿昨天的名单冒充今天。
    """
    try:
        r = con.execute("SELECT MAX(date) FROM stock_indicators_daily").fetchone()
    except Exception:  # noqa: BLE001
        log.exception("开源规则：取最近交易日失败")
        return "", {}
    latest = str((r and r[0]) or "")
    if not latest:
        return "", {}
    key = _oss_db_key(con)
    now = time.time()
    with _OSS_SNAP_LOCK:
        cache = _OSS_SNAP
        if (cache["key"] == key and cache["date"] == latest and cache["snap"]
                and now - float(cache["at"] or 0.0) <= _OSS_SNAP_TTL):
            return latest, cache["snap"]
    snap = _build_oss_snapshot(con, latest)
    if snap:
        with _OSS_SNAP_LOCK:
            _OSS_SNAP.update({"key": key, "date": latest, "at": now, "snap": snap})
    return latest, snap


# ---- 各条规则的判据 ----------------------------------------------
# 统一签名：(快照记录, 参数) -> (是否命中, 给人看的一句话, 排序分)
# 那句话必须**同时**能当「命中说明」和「淘汰原因」读 —— 因为淘汰者要能看懂自己
# 死在哪一条上（不知道一只票为什么被剔，漏斗就是黑箱）。
_WIN_FIELDS = ("ret1", "ret2", "ret5", "mom20")
_WIN_CN = {"ret1": "当日涨幅", "ret2": "2 日涨幅", "ret5": "5 日涨幅", "mom20": "20 日涨幅"}


def _win_of(r: _Snap, p: dict) -> tuple[str, float | None]:
    """取「看哪个窗口」的参数值。枚举外的值一律退回 mom20，不让一个脏参数把工具跑崩。"""
    w = str(p.get("win") or "mom20")
    if w not in _WIN_FIELDS:
        w = "mom20"
    return w, getattr(r, w, None)


def _p_ma_align(r: _Snap, p: dict):
    if not (r.ma5 and r.ma20 and r.ma60):
        return False, "均线数据缺失（当日 MA5/MA20/MA60 有空值）", 0.0
    txt = "收盘 %.2f / MA5 %.2f / MA20 %.2f / MA60 %.2f" % (
        r.close, r.ma5, r.ma20, r.ma60)
    if r.close > r.ma5 > r.ma20 > r.ma60:
        return True, txt + "（多头排列）", round(float(r.ma20_dev or 0.0), 2)
    return False, "均线未成多头排列（" + txt + "）", 0.0


def _p_near_high(r: _Snap, p: dict):
    gap = _num(p.get("max_gap"), 25.0)
    d = r.dist_high250
    if d is None:
        return False, "没有 52 周高点可算（历史不足 251 个交易日）", 0.0
    if d >= -gap:
        return True, "距 52 周最高收盘 %+.1f%%（在 %.0f%% 之内）" % (d, gap), round(d, 2)
    return False, "距 52 周最高收盘 %+.1f%%，已超过 %.0f%% 的门槛" % (d, gap), 0.0


def _p_burst_vol(r: _Snap, p: dict):
    min_ret = _num(p.get("min_ret"), 4.0)
    min_vr = _num(p.get("min_vr"), 1.5)
    if r.ret1 is None:
        return False, "算不出当日涨幅（缺前一日收盘）", 0.0
    if r.volume_ratio is None:
        return False, "量比缺失（当日成交量为 0 或未入库）", 0.0
    if r.ret1 < min_ret:
        return False, "当日涨幅 %.2f%% < %.1f%%（涨幅不够）" % (r.ret1, min_ret), 0.0
    if r.volume_ratio < min_vr:
        return False, "量比 %.2f < %.2f（涨了，但没放量）" % (r.volume_ratio, min_vr), 0.0
    return True, "涨幅 %.2f%%（≥%.1f%%）· 量比 %.2f（≥%.2f）" % (
        r.ret1, min_ret, r.volume_ratio, min_vr), round(r.ret1, 2)


def _p_burst(r: _Snap, p: dict):
    min_ret = _num(p.get("min_ret"), 4.0)
    if r.ret1 is None:
        return False, "算不出当日涨幅（缺前一日收盘）", 0.0
    if r.ret1 >= min_ret:
        return True, "当日涨幅 %.2f%%（≥%.1f%%）" % (r.ret1, min_ret), round(r.ret1, 2)
    return False, "当日涨幅 %.2f%% < %.1f%%（没到门槛）" % (r.ret1, min_ret), 0.0


def _p_pullback(r: _Snap, p: dict):
    lo = _num(p.get("min_dev"), -3.0)
    hi = _num(p.get("max_dev"), 0.0)
    if lo > hi:                       # 用户把上下界调反了：按区间处理，不报错
        lo, hi = hi, lo
    d = r.ma20_dev
    if d is None:
        return False, "MA20 缺失（上市不足 20 个交易日 / 长期停牌）", 0.0
    if lo <= d <= hi:
        return True, "距 MA20 %+.2f%%（区间 %+.0f%% ~ %+.0f%%）" % (d, lo, hi), round(-d, 2)
    if d < lo:
        return False, "距 MA20 %+.2f%%（跌破 %.0f%%，回踩已经变成破位）" % (d, lo), 0.0
    return False, "距 MA20 %+.2f%%（高出 %.0f%%，还没回踩到位）" % (d, hi), 0.0


def _p_shrink(r: _Snap, p: dict):
    mx = _num(p.get("max_vr"), 0.7)
    vr = r.volume_ratio
    if vr is None:
        return False, "量比缺失（当日成交量为 0 或未入库）", 0.0
    if vr <= mx:
        return True, "量比 %.2f（≤%.2f，缩量）" % (vr, mx), round((1.0 - vr) * 100.0, 2)
    return False, "量比 %.2f > %.2f（没缩到门槛以下）" % (vr, mx), 0.0


def _p_mom(r: _Snap, p: dict):
    w, v = _win_of(r, p)
    thr = _num(p.get("min_mom"), 20.0)
    cn = _WIN_CN[w]
    if v is None:
        return False, "%s算不出（该票历史 K 线不足）" % cn, 0.0
    if v >= thr:
        return True, "%s %+.2f%%（≥%.0f%%）" % (cn, v, thr), round(v, 2)
    return False, "%s %+.2f%% < %.0f%%（涨得不够）" % (cn, v, thr), 0.0


def _p_reversal(r: _Snap, p: dict):
    w, v = _win_of(r, p)
    thr = _num(p.get("max_mom"), -20.0)
    cn = _WIN_CN[w]
    if v is None:
        return False, "%s算不出（该票历史 K 线不足）" % cn, 0.0
    if v <= thr:
        return True, "%s %+.2f%%（≤%.0f%%，超跌）" % (cn, v, thr), round(-v, 2)
    return False, "%s %+.2f%% > %.0f%%（还没跌够）" % (cn, v, thr), 0.0


def _p_high_vol(r: _Snap, p: dict):
    thr = _num(p.get("min_atr"), 6.0)
    v = r.atr_pct
    if v is None:
        return False, "ATR 缺失，算不出波动率", 0.0
    if v >= thr:
        return True, "ATR 占股价 %.2f%%（≥%.1f%%）" % (v, thr), round(v, 2)
    return False, "ATR 占股价 %.2f%% < %.1f%%（波动不够大）" % (v, thr), 0.0


def _p_rsi(r: _Snap, p: dict):
    thr = _num(p.get("min_rsi"), 80.0)
    v = r.rsi6
    if v is None:
        return False, "RSI6 缺失", 0.0
    if v >= thr:
        return True, "RSI6 %.1f（≥%.0f，超买）" % (v, thr), round(v, 1)
    return False, "RSI6 %.1f < %.0f（没进超买区）" % (v, thr), 0.0


