def _res_cards(con, codes, want_tiers: set) -> tuple[list, dict, dict, dict]:
    bd = _latest(con, "SELECT MAX(build_date) FROM res_stock_card")
    if not bd:
        return [], {c: "共振卡尚无批次数据" for c in codes}, {}, {"build_date": ""}
    kept, dropped, score, marks = [], {}, {}, {}
    CH = 400
    got = {}
    for i in range(0, len(codes), CH):
        chunk = codes[i:i + CH]
        ph = ",".join("?" * len(chunk))
        for r in con.execute(
                "SELECT code,tier,res_score FROM res_stock_card"
                " WHERE build_date=? AND code IN (%s)" % ph, [bd] + chunk):
            got[str(r[0])] = (r[1], r[2])
    for c in codes:
        t = got.get(c)
        if not t:
            dropped[c] = "不在 %s 共振卡内（当日无多源证据）" % bd
            continue
        tier, rs = t
        if str(tier) not in want_tiers:
            dropped[c] = "共振 %s 档（本工具只保留 %s）" % (tier, "/".join(sorted(want_tiers)))
            continue
        kept.append(c)
        score[c] = float(rs or 0)
        marks[c] = "共振 %s 档 · %.1f 分" % (tier, float(rs or 0))
    return kept, dropped, score, {"marks": marks, "build_date": bd}


