def _add_col_if_missing(con: sqlite3.Connection, table: str, col: str, ddl: str) -> bool:
    """给已存在的表补列（老库没法重建：`CREATE TABLE IF NOT EXISTS` 不会加列）。

    为什么必须做：项目里已经有 app.db，`executescript(DDL)` 对已存在的表是空操作。
    不加这一步，新列只会在全新机器上存在，老机器上 `SELECT pillars` 直接报错。
    """
    cols = {r[1] for r in con.execute("PRAGMA table_info(%s)" % table)}
    if col in cols:
        return False
    con.execute("ALTER TABLE %s ADD COLUMN %s %s" % (table, col, ddl))
    return True


def ensure_tables(con: sqlite3.Connection) -> None:
    con.executescript(DDL)
    # 2026-11-03：工具必须标明「适用哪个板块」，否则无法回答"谁适合短线、谁适合中线"。
    # 这是结构性补丁，老库走 ALTER 补齐。
    _add_col_if_missing(con, "tool_registry", "pillars",
                        "TEXT NOT NULL DEFAULT ''")
    _add_col_if_missing(con, "tool_registry", "pillar_note",
                        "TEXT NOT NULL DEFAULT ''")
    # 2026-11-05：11 条开源规则降为「说明性标注」——不参与进出决策，但不下架。
    # 老库必须就地补列（DROP/重建会把人工改过的 status 一起丢掉）。
    _add_col_if_missing(con, "tool_registry", "advisory",
                        "INTEGER NOT NULL DEFAULT 0")
    # 2026-11-06（审计 T01）：资格契约表。**这是"能不能用"与"算不算得出来"的分界**：
    # tool_registry 回答"货架上有什么"，tool_contract 回答"今天该不该开这把工具"。
    # 同步放在这里而不是启动钩子：任何拿到 conn 的入口（页面/筛台/脚本/回测）
    # 都会 ensure_tables，契约就不会出现"页面有、脚本没有"的两套判定。
    try:
        from viewer import tool_contract as _tc
        _st = _tc.sync(con)
        log.info("工具资格契约已载入：%s", _st)
    except Exception:  # noqa: BLE001
        # 契约载入失败不阻断服务（否则整个查看器打不开），但必须留下痕迹：
        # 此时所有工具都会被 evaluate() 判成"无契约、不得决策"，是安全的失败方向。
        log.exception("工具资格契约载入失败 —— 所有工具将按「无契约」判定为不可决策")
    con.commit()


