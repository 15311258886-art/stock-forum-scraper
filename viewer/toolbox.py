def _apply_oss(tool_key: str):
    """把一个开源规则包成筛台工具（统一契约：apply(con, codes, params) -> dict）。

    ★ **逐只独立判断**：只看这只票自己的字段，不看池子分布、不做排名截断。
      筛台「每个工具对全宇宙只算一次、之后只做集合求交」就建立在这一条上；
      任何「取涨幅前 10%」之类的写法都会让结果随输入池变化，求交出来的数是错的。
    """
    pred = _OSS_PRED[tool_key]

    def _f(con, codes, params) -> dict:
        prm = params or {}
        skip_st = bool(int(_num(prm.get("skip_st"), 0)))
        skip_lu = bool(int(_num(prm.get("skip_limit_up"), 0)))
        td, snap = oss_snapshot(con)
        if not snap:
            return _res([], {c: "取不到最近交易日的行情（指标表为空 / 还没入库）" for c in codes},
                        {}, "开源规则：最近交易日没有可用行情，本工具暂时算不出来")
        kept, dropped, score, marks = [], {}, {}, {}
        for c in codes:
            r = snap.get(c)
            if r is None:
                dropped[c] = "不在 %s 的行情表里（当日停牌 / 未入库）" % td
                continue
            if skip_st and _is_st(r.name):
                dropped[c] = "名称含 ST（%s），按参数剔除 —— ST 股涨跌幅只有 5%%，" \
                             "混进来会让量价判据失真" % (r.name or c)
                continue
            if skip_lu and r.ret1 is not None and r.ret1 >= _limit_up_thr(c):
                dropped[c] = "当日涨幅 %.2f%% 已达涨停（门槛 %.1f%%），按参数剔除" % (
                    r.ret1, _limit_up_thr(c))
                continue
            ok, why, sc = pred(r, prm)
            if not ok:
                dropped[c] = why
                continue
            kept.append(c)
            score[c] = sc
            marks[c] = why
        # note 里用**中文工具名**，不露 tool_key：这段会显示在筛台的每一级上，
        # 用户不该在界面上看到 `ma_align` 这种内部标识。
        cn = _BY_KEY.get(tool_key, {}).get("name") or tool_key
        note = "%s · 数据日 %s：%d 只 → %d 只" % (cn, td, len(codes), len(kept))
        return _res(kept, dropped, score, note, {"marks": marks})

    return _f


