def score_sentiment(text: str) -> tuple[str, float]:
    """中英混合情绪打分 → (看多/看空/中性, 分值)。"""
    if not text:
        return "中性", 0.0
    low = text.lower()
    pos = neg = 0.0
    for w in BULL_EN:
        c = low.count(w)
        if c:
            pos += c * _INTENSITY.get(w, 1.0)
    for w in BEAR_EN:
        c = low.count(w)
        if c:
            neg += c * _INTENSITY.get(w, 1.0)
    for w in BULL_ZH:
        pos += text.count(w) * _INTENSITY.get(w, 1.0)
    for w in BEAR_ZH:
        neg += text.count(w) * _INTENSITY.get(w, 1.0)
    score = pos - neg
    if score > 0:
        return "看多", round(score, 2)
    if score < 0:
        return "看空", round(score, 2)
    return "中性", 0.0


def extract_symbols(text: str) -> list[dict]:
    """抽取标的：美股代码 / 港股代码 / A股代码 / 公司关键词。返回 [{market,symbol,name}]。"""
    out: list[dict] = []
    seen: set[tuple[str, str]] = set()

    def add(market: str, sym: str, name: str = ""):
        key = (market, sym)
        if key in seen:
            return
        seen.add(key)
        out.append({"market": market, "symbol": sym, "name": name or US_HK_SYMBOLS.get(sym, "")})

    for m in CODE_CN.finditer(text):
        add("CN", m.group(1))
    for m in CODE_HK.finditer(text):
        add("HK", m.group(1).zfill(4))
    for m in CODE_US.finditer(text):
        t = m.group(1).upper()
        if t in _NOT_TICKER or len(t) < 2:
            continue
        if t in US_HK_SYMBOLS:           # 仅接受知识表内的美股代码，避免英文词误判
            add("US", t, US_HK_SYMBOLS[t])
    # 中文公司名关键词 → 标的
    for sym, name in US_HK_SYMBOLS.items():
        if name and name in text and len(name) >= 2:
            add("US" if sym.isalpha() else "HK", sym, name)
    return out


_KW_RE_CACHE: dict[str, "re.Pattern[str]"] = {}


def _count_kw(low: str, kw: str) -> int:
    """统计关键词命中次数。

    英文/含字母关键词用**词边界**匹配——否则 "war" 会命中 "starwars"/"software"、
    "ai" 会命中 "said"，造成大面积误分类；纯中文关键词仍用子串匹配。
    """
    kl = (kw or "").lower().strip()
    if not kl:
        return 0
    if any("a" <= ch <= "z" for ch in kl):
        pat = _KW_RE_CACHE.get(kl)
        if pat is None:
            pat = re.compile(r"(?<![a-z0-9])" + re.escape(kl) + r"(?![a-z0-9])")
            _KW_RE_CACHE[kl] = pat
        return len(pat.findall(low))
    return low.count(kl)


def classify_topic(text: str, topics: dict[str, list[str]] | None = None) -> tuple[str, list[str]]:
    """归类到驱动主题（返回主主题 + 全部命中主题）。"""
    topics = topics or {}
    low = (text or "").lower()
    hits: list[tuple[str, int]] = []
    for topic, kws in topics.items():
        n = sum(_count_kw(low, k) for k in kws)
        if n:
            hits.append((topic, n))
    if not hits:
        return "其他", []
    hits.sort(key=lambda x: x[1], reverse=True)
    return hits[0][0], [h[0] for h in hits]


