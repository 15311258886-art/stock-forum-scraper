def match_transmission(text: str) -> list[dict]:
    """把一段文本匹配到「海外主题 → 国内板块」传导条目（可命中多条）。

    与 classify_topic 一致，使用词边界匹配，避免 "war" 命中 "starwars" 之类的误判。
    """
    low = (text or "").lower()
    out = []
    for row in TRANSMISSION_TABLE:
        hit = [k for k in row["trigger"] if _count_kw(low, k)]
        if hit:
            out.append({**row, "matched": hit})
    return out


def sector_of_symbol(symbol: str) -> list[str]:
    """从传导表反查某标的所属的国内板块。"""
    sectors: list[str] = []
    for row in TRANSMISSION_TABLE:
        for sym, _ in row["symbols"]:
            if sym == symbol:
                sectors.extend(row["sectors"])
    return sorted(set(sectors))
