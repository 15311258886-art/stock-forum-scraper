# 别名：规则映射出来的板块名可能带修饰词，这里给几个高频的同义写法
_SECTOR_ALIAS = {
    "券商": ["券商", "证券"],
    "半导体": ["半导体", "芯片"],
    "房地产": ["房地产", "地产"],
    "粮食": ["农业"],
    "农产品": ["农业"],
}


def leaders(sector: str, top: int = 8):
    """板块 → [(code, name), ...]，按知名度降序。取不到返回 []。"""
    lst = SECTOR_LEADERS.get(sector)
    if lst is None:
        for k, alts in _SECTOR_ALIAS.items():
            if sector in alts:
                lst = SECTOR_LEADERS.get(k)
                break
    if not lst:
        return []
    return [(c, n) for c, n in lst[:max(1, int(top or 8))]]


def codes(sector: str, top: int = 8) -> list:
    """板块 → 代码列表（顺序即展示顺序）。"""
    return [c for c, _ in leaders(sector, top)]


def known_sectors() -> list:
    """已备名单的板块（供自检 / 文档用）。"""
    return sorted(SECTOR_LEADERS.keys())
