def _topn_verdict(r):
    """先看样本，再看经济量级，最后看「同槽随机」是否也能拿到同样的改善。

    判据用**净增量** `net = Δm − 同槽对照 Δm`，不是裸 Δm：
    同槽对照（随机换掉同样多的头部席位）能拿到的那部分改善，属于「排序噪声」，
    不是规则的信息。裸 Δm 过 0.25pp 就判「可用」，会把噪声记成功劳。
    """
    if r is None:
        return "交集为空", ""
    if r["n_cmp"] < 30:
        return "样本不足", ""
    d = r["d_m"]
    ctrl = r["d_mc2"] or 0.0
    net = d - ctrl
    if abs(net) >= 0.25 and abs(r["d_m_t"] or 0) >= 2:
        v = "可用"
    elif abs(d) >= 0.05:
        v = "有信息但不可用"
    else:
        v = "无经济意义"
    flag = "⚠ 不如瞎换" if (d > 0) != (net > 0) else ""
    return v, flag


