def _load(stamp: str) -> dict:
    out = {}
    for key, label, pat in CONFIGS:
        p = LOG / (pat % stamp if "%s" in pat else pat)
        if not p.exists():
            continue
        out[key] = {"label": label, "path": p, "data": json.loads(p.read_text(encoding="utf-8"))}
    return out


def _f(x, nd=3, sign=False):
    if x is None:
        return "—"
    try:
        if x != x:          # NaN：宁可留空，也不要在表里印 +nan
            return "—"
    except TypeError:
        pass
    fmt = ("%%+.%df" % nd) if sign else ("%%.%df" % nd)
    return fmt % x


