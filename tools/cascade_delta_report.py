# 预注册判据漏了「量级必须够」这一条（写的时候只写了方向 + 单调）。
# 事后补一个量级门槛，**不改预注册结果**，另起一列并标明是事后加的：
#   |D10−D1| < 0.25pp → 量级为零（不管 ρ 多漂亮）
#   方向 + 单调都过，且 |日内 ρ 的 t| ≥ 2 → 显著
DEC_FLOOR = 0.25
DEC_MIN_DAYS = 300           # 可比日少于 300 天 → 样本不足，任何判读都不成立
DEC_EFF_SHORT = {
    "反了（显著）": "**反·显著**",
    "反了（不显著）": "反·不显著",
    "方向对（显著）": "对·显著",
    "方向对（不显著）": "对·不显著",
    "量级为零": "量级≈0",
    "无排序能力": "无能力",
    "样本不足": "样本不足",
    "无样本": "—",
}


def _dec_eff(r):
    """事后补的实质判定：先看样本，再看量级、方向 + 单调，最后看日内 ρ 的 t。"""
    if not r or not r.get("n_days"):
        return "无样本"
    if r["n_days"] < DEC_MIN_DAYS:
        return "样本不足"
    d, rho, rt = r.get("d10_minus_d1"), r.get("rho_deciles"), r.get("rho_daily_t")
    if d is None or rho is None:
        return "无样本"
    if abs(d) < DEC_FLOOR:
        return "量级为零"
    sig = abs(rt or 0) >= 2.0
    if d < 0 and rho <= -0.5:
        return "反了（显著）" if sig else "反了（不显著）"
    if d > 0 and rho >= 0.5:
        return "方向对（显著）" if sig else "方向对（不显著）"
    return "无排序能力"


